#!/usr/bin/env node
/* Embed the full-size ability score art as CSS for the self-contained play_game.html. */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const sourceDir = path.join(root, "ICONS", "Ability_score");
const output = path.join(root, "web", "mygame", "ability_score_icons.css");
const names = {
  STR: "Strength",
  DEX: "Dexterity",
  CON: "Constitution",
  INT: "Intelligence",
  WIS: "Wisdom",
  CHA: "Charisma"
};
const rules = [];
for (const [ability, name] of Object.entries(names)) {
  const png = fs.readFileSync(path.join(sourceDir, name + "_Score_Icon.png"));
  rules.push("#statSidebar .sbAbilTile[data-ability=\"" + ability + "\"]::before { background-image: url(data:image/png;base64," + png.toString("base64") + "); }");
}
const body = "/* Generated by tools/gen_ability_score_icons.js from ICONS/Ability_score/*_Score_Icon.png. */\n" + rules.join("\n") + "\n";
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8").replace(/\r\n/g, "\n") !== body) {
    console.error("ability_score_icons.css is stale; run node tools/gen_ability_score_icons.js");
    process.exit(1);
  }
  console.log("ability_score_icons.css is up to date");
} else {
  fs.writeFileSync(output, body);
  console.log("wrote " + path.relative(root, output));
}

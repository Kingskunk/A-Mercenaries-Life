#!/usr/bin/env node
/*
 * gen_city_data.js -- generates web/mygame/city-data.generated.js, the district table the sidebar's Travel button reads (web/mygame/citytravel.js).
 *
 * WHY: the walk between districts costs the sum of both ends' distances from the compound (port_valen.txt get_district_distance), and the sidebar has to show those minutes
 * before the player picks. Rather than copy the numbers into JS (drift risk), this reads them from the scene itself, so the button and the scene can never disagree. The names
 * and the "open" flags are the only hand-kept part, listed in CITIES below, and match the bold names on port_valen_travel's menu.
 *
 * Run via `node tools/gen_city_data.js` (compile.js runs it before bundling). It throws if a district is missing from the scene, rather than emitting a wrong table.
 *
 * ADDING A CITY: add an entry to CITIES (its scene file, the label that holds the distances, the variable that says where the player stands, the variable the walk option reads the
 * destination from, and its districts), give each of its hubs the hidden "↦ Walk to the district picked on the sidebar. [<id>]" option, and write the city's walk label
 * (see port_valen.txt port_valen_walk_picked). citytravel.js needs no change.
 */
"use strict";
const fs = require("fs"), path = require("path");

const SCENES = path.join(__dirname, "..", "web", "mygame", "scenes");
const OUT = path.join(__dirname, "..", "web", "mygame", "city-data.generated.js");

const CITIES = {
  port_valen: {
    name: "Port Valen",
    file: "port_valen/port_valen.txt",
    distanceLabel: "get_district_distance",
    districtVar: "gdd_district",
    distanceVar: "gdd_distance",
    hereVar: "current_district",      // where the player stands
    destVar: "pv_travel_dest",         // where the walk option reads the destination from
    districts: [
      { id: "compound", name: "The Carrion Compound", open: "" },
      { id: "harbor", name: "Harbor Quayside", open: "" },
      { id: "civic_heights", name: "Civic Heights", open: "civic_heights_open" },
      { id: "upper_wharves", name: "The Patrician Quarter", open: "upper_wharves_open" },
      { id: "dredge_end", name: "Dredge-End", open: "dredge_end_open" },
      { id: "middle_ward", name: "The Middle Ward", open: "middle_ward_open" }
    ]
  }
};

function distances(city) {
  const text = fs.readFileSync(path.join(SCENES, city.file), "utf8").replace(/\r\n/g, "\n");
  const start = text.indexOf("*label " + city.distanceLabel + "\n");
  if (start < 0) throw new Error(city.file + ": no label " + city.distanceLabel);
  const end = text.indexOf("\n*return", start);
  const body = text.slice(start, end);
  const out = {};
  const re = new RegExp("\\*if \\(" + city.districtVar + " = \"([a-z_]+)\"\\)\\n\\s+\\*set " + city.distanceVar + " (\\d+)", "g");
  let m;
  while ((m = re.exec(body))) out[m[1]] = Number(m[2]);
  return out;
}

const data = {};
Object.keys(CITIES).forEach(function (id) {
  const c = CITIES[id], d = distances(c);
  data[id] = {
    name: c.name, hereVar: c.hereVar, destVar: c.destVar,
    districts: c.districts.map(function (x) {
      // the compound is the origin (0 minutes): the scene sets gdd_distance 0 before any *if
      const dist = x.id === "compound" ? 0 : d[x.id];
      if (dist === undefined) throw new Error(c.file + ": no distance for district " + x.id);
      return { id: x.id, name: x.name, dist: dist, open: x.open };
    })
  };
});

const text = "// GENERATED by tools/gen_city_data.js from the scenes' district distances -- do not edit; edit the scene or CITIES in the generator and run it.\n" +
  "window.CITY_TRAVEL = " + JSON.stringify(data, null, 1) + ";\n";
const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (old !== text) { fs.writeFileSync(OUT, text); console.log("gen_city_data: wrote " + path.relative(process.cwd(), OUT)); }
else console.log("gen_city_data: city-data.generated.js is up to date.");

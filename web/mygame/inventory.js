  function showTip(el, html) {
    if (!html) { hideTip(); return; }
    elTip.innerHTML = html;
    elTip.className = "inv-tip on";
    // Positioned inside the dialog in CSS pixels, which the screen-fit zoom scales (index.html, window.UI_ZOOM): measure in viewport pixels, divide by the zoom.
    var z = window.UI_ZOOM || 1;
    var d = dlg.getBoundingClientRect(), r = el.getBoundingClientRect(), t = elTip.getBoundingClientRect();
    // The card lives inside the dialog, and everything inside is clipped to its PADDING box (inside the bronze frame, which is a border of a few CSS pixels), so
    // the card is kept within that box, not the outer edge: clamped there, and measured from there, since an absolutely positioned child's origin is the padding box.
    var cs = window.getComputedStyle(dlg);
    var bl = parseFloat(cs.borderLeftWidth) || 0, br = parseFloat(cs.borderRightWidth) || 0, bt = parseFloat(cs.borderTopWidth) || 0, bb = parseFloat(cs.borderBottomWidth) || 0;
    var padL = d.left + bl * z, padR = d.right - br * z, padT = d.top + bt * z, padB = d.bottom - bb * z, gap = 6 * z;
    var left, top;
    if (el.parentNode && el.parentNode.classList && el.parentNode.classList.contains("inv-fig")) {
      // a slot in one of the side columns: the card goes beside it, over the figure, so it never hides the slot above or below
      var onLeft = (r.left + r.width / 2) < (d.left + d.width / 2);
      left = onLeft ? r.right + 10 * z : r.left - t.width - 10 * z;
      top = r.top + r.height / 2 - t.height / 2;
    } else {
      left = r.left + r.width / 2 - t.width / 2;
      top = r.top - t.height - 8 * z;
      if (top < padT + gap) top = r.bottom + 8 * z;
    }
    left = Math.min(Math.max(padL + gap, left), padR - t.width - gap);
    top = Math.max(padT + gap, Math.min(top, padB - t.height - gap));
    elTip.style.left = ((left - padL) / z) + "px";
    elTip.style.top = ((top - padT) / z) + "px";
  }
  function onOver(ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest("[data-item], [data-citem], [data-slot]") : null;
    if (!t || view.drag) { if (!t) hideTip(); return; }
    if (t.hasAttribute("data-citem")) showTip(t, tipHtmlForItem(stowedEntry(view.left, t.getAttribute("data-citem"), statsNow()) || {}));
    else if (t.hasAttribute("data-item")) showTip(t, tipHtmlForItem(findOwned(t.getAttribute("data-item")) || {}));
    else showTip(t, tipHtmlForSlot(t.getAttribute("data-slot"), t.getAttribute("data-ring") || ""));
  }

  /* ---------------------------------------------------------------- drag and drop */

  function onDragStart(ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest("[data-item]") : null;
    if (!t || !findOwned(t.getAttribute("data-item"))) return;
    view.drag = t.getAttribute("data-item");
    try { ev.dataTransfer.setData("text/plain", view.drag); ev.dataTransfer.effectAllowed = "move"; } catch (e) { /* some browsers refuse; the drop reads view.drag */ }
    hideTip();
    // mark the slots that take it, without rebuilding the DOM mid-drag (that would cancel the drag)
    var r = findOwned(view.drag);
    Array.prototype.forEach.call(dlg.querySelectorAll("[data-slot]"), function (el) { if (accepts(r, el.getAttribute("data-slot"))) el.classList.add("inv-accepts"); });
  }
  function onDragEnd() {
    view.drag = null;
    Array.prototype.forEach.call(dlg.querySelectorAll(".inv-accepts, .inv-over"), function (el) { el.classList.remove("inv-accepts", "inv-over"); });
  }
  function onDragOver(ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest("[data-slot]") : null;
    Array.prototype.forEach.call(dlg.querySelectorAll(".inv-over"), function (el) { if (el !== t) el.classList.remove("inv-over"); });
    if (!t || !view.drag) return;
    if (accepts(findOwned(view.drag), t.getAttribute("data-slot"))) { ev.preventDefault(); t.classList.add("inv-over"); }
  }
  function onDrop(ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest("[data-slot]") : null;
    var id = view.drag;
    if (!t || !id) return;
    ev.preventDefault();
    var r = findOwned(id), bucket = t.getAttribute("data-slot");
    view.drag = null;
    if (accepts(r, bucket)) equipTo(bucket, r.equip.id, t.getAttribute("data-ring") || undefined);
    else render();
  }

  // Consumables are used through the game's own dossier (real ChoiceScript: equipment.txt use_consumable is the only
  // place an effect is written, so nothing is mirrored here). The Use button runs a one-shot label (choicescript_stats codex_use_now) that uses the item and hands
  // the player straight back to their page with a one-line result (spell_cast_toast), as the sidebar's Cast button does (2026-10-19, the user: no result page to click out of). Not offered
  // mid-fight (the fight has its own item option) or while the dossier is already open. "Open" is the running scene being the stats
  // scene, not the Show Stats button's data-return marker: closing the dossier from its own menu leaves that marker set.
  function canUse() {
    var sc = statsNow().scene;
    if (sc && sc.secondaryMode === "stats") return false;
    return !truthy(statsNow().combat_engaged) && typeof window.Scene === "function" && typeof window.clearScreen === "function" && !!window.nav;
  }
  function useItem(id) {
    if (!canUse()) return;
    statsNow().use_item_id = id;
    close();
    var scene = new window.Scene("choicescript_stats", window.stats, window.nav, { secondaryMode: "stats", saveSlot: "temp" });
    scene.targetLabel = { label: "codex_use_now", origin: "url", originLine: 0 };
    window.clearScreen(function () {
      if (typeof window.setButtonTitles === "function") window.setButtonTitles();
      scene.execute();
    });
  }

  // A piece with an ability-score bonus (item.statBonus, from the catalog's traits) cannot be swapped here: the scores,
  // max HP and AC are re-derived by ChoiceScript (startup.txt recalculate_equipment_bonuses), so the swap is handed to
  // the dossier exactly like the Use button. Applies when the piece going on OR coming off carries a bonus.
  function hasStatBonus(bucket, id) {
    return data().items.some(function (item) {
      return item.statBonus && item.equip && item.equip.slot === bucket && item.equip.id === id;
    });
  }
  // Attuning the Hearthstone changes CON and max HP, so ChoiceScript does it (choicescript_stats codex_attune_do); not available during a fight, like any hand-off.
  function attuneViaDossier(action) {
    if (!canUse()) { note("Attunement is changed from the dossier, and not in the middle of a fight."); render(); return; }
    statsNow().attune_action = action;
    close();
    var scene = new window.Scene("choicescript_stats", window.stats, window.nav, { secondaryMode: "stats", saveSlot: "temp" });
    scene.targetLabel = { label: "codex_attune_do", origin: "url", originLine: 0 };
    window.clearScreen(function () {
      if (typeof window.setButtonTitles === "function") window.setButtonTitles();
      scene.execute();
    });
  }
  function equipViaDossier(bucket, id) {
    if (!canUse()) { note("That piece changes an ability score, so it is put on from the dossier, and not in the middle of a fight."); render(); return; }
    var st = statsNow();
    st.equip_slot = bucket;
    st.equip_item_id = id;
    close();
    var scene = new window.Scene("choicescript_stats", window.stats, window.nav, { secondaryMode: "stats", saveSlot: "temp" });
    scene.targetLabel = { label: "codex_equip_do", origin: "url", originLine: 0 };
    window.clearScreen(function () {
      if (typeof window.setButtonTitles === "function") window.setButtonTitles();
      scene.execute();
    });
  }

  // Where the option list for a slot sits: just under the tile, or above it when there is no room below, kept inside the doll column. Measured in viewport
  // pixels and set in CSS pixels (the screen-fit zoom, window.UI_ZOOM), the same rule the hover cards follow.
  function placePop() {
    var pop = elDoll.querySelector(".inv-pop");
    if (!pop || !view.pop || !view.pop.anchor) return;
    var z = window.UI_ZOOM || 1, a = view.pop.anchor, dr = elDoll.getBoundingClientRect(), pr = pop.getBoundingClientRect();
    var left = Math.min(Math.max(dr.left + 4, a.left + a.width / 2 - pr.width / 2), dr.right - pr.width - 4);
    var top = a.bottom + 6;
    if (top + pr.height > dr.bottom - 4) top = a.top - pr.height - 6;
    pop.style.left = ((left - dr.left) / z) + "px";
    pop.style.top = ((top - dr.top) / z) + "px";
    pop.style.visibility = "visible";
  }

  function quickAct(id) {
    var r = findOwned(id);
    if (!r) return;
    if (r.equip) {
      var bucket = r.equip.slot;
      equipTo(bucket, r.equip.id, bucket === "ring" ? ringTarget(r.equip.id) : undefined);
    } else if (r.use) {
      useItem(r.id);
    }
  }

  function onClick(ev) {
    var t = ev.target && ev.target.closest ? ev.target.closest("[data-act], [data-cat], [data-item], [data-slot], [data-pop-id], [data-pop-shield], [data-attune], [data-swap-sidearm], [data-equip-sel], [data-use], [data-left], [data-citem], [data-qty], [data-qty-set], [data-xfer]") : null;
    if (!t || !dlg.contains(t)) {
      if (view.pop) { view.pop = null; render(); }   // a click on empty space puts the option list away
      return;
    }
    var act = t.getAttribute("data-act");
    if (act === "close") return close();
    if (act === "trade") {
      // The trade panel (trade.js) sits over the shop menus; from here it is one tap away.
      close();
      if (window.TradePanel) window.TradePanel.open();
      return;
    }
    if (t.hasAttribute("data-left")) {
      view.left = t.getAttribute("data-left"); view.sel = null; view.csel = null; view.pop = null; view.qty = 1; note("");
      render();
      return;
    }
    if (t.hasAttribute("data-citem")) {
      var cid2 = t.getAttribute("data-citem");
      if (ev.shiftKey) { doMove("take", cid2, 99999); return; }   // shift-click takes the whole stack back
      view.csel = view.csel === cid2 ? null : cid2; view.sel = null; view.qty = 1; note("");
      render();
      return;
    }
    if (t.hasAttribute("data-qty") || t.hasAttribute("data-qty-set") || t.hasAttribute("data-xfer")) {
      if (t.disabled) return;
      var xc2 = xferContext(statsNow());
      if (!xc2 || !xc2.sel || !xc2.dir) return;
      var cur = Math.max(1, Math.min(view.qty, xc2.max || 1));
      if (t.hasAttribute("data-qty")) { view.qty = Math.max(1, Math.min(xc2.max, cur + Number(t.getAttribute("data-qty")))); render(); return; }
      if (t.hasAttribute("data-qty-set")) { var v = t.getAttribute("data-qty-set"); view.qty = v === "all" ? xc2.max : Math.min(xc2.max, Number(v)); render(); return; }
      doMove(xc2.dir, xc2.sel.id, cur);
      return;
    }
    if (t.hasAttribute("data-use")) { if (!t.disabled) useItem(t.getAttribute("data-use")); return; }
    if (t.hasAttribute("data-cat")) { view.category = t.getAttribute("data-cat"); render(); return; }
    if (t.hasAttribute("data-item")) {
      var id = t.getAttribute("data-item");
      if (ev.shiftKey && view.left !== "you") { var carried = findOwned(id); if (carried && carried.stow) { doMove("stow", id, 99999); return; } }   // shift-click moves the whole stack into the open container
      view.sel = view.sel === id ? null : id; view.csel = null; view.qty = 1;
      view.pop = null; note("");
      render();
      return;
    }
    if (t.hasAttribute("data-slot")) {
      var bucket = t.getAttribute("data-slot"), ring = t.getAttribute("data-ring") || "";
      var picked = view.sel ? findOwned(view.sel) : null;
      if (picked && accepts(picked, bucket)) { equipTo(bucket, picked.equip.id, ring || undefined); return; }
      var wasOpen = view.pop && view.pop.bucket === bucket && (view.pop.ring || "") === ring;
      var rect = t.getBoundingClientRect();
      view.pop = wasOpen ? null : { bucket: bucket, ring: ring, anchor: { left: rect.left, top: rect.top, bottom: rect.bottom, width: rect.width } };
      view.sel = null; note("");
      render();
      return;
    }
    if (t.hasAttribute("data-pop-id")) { equipTo(view.pop.bucket, t.getAttribute("data-pop-id"), view.pop.ring || undefined); return; }
    if (t.hasAttribute("data-pop-shield")) { equipTo("shield"); return; }
    if (t.hasAttribute("data-attune")) { attuneViaDossier(t.getAttribute("data-attune")); return; }
    if (t.hasAttribute("data-equip-sel")) {
      var r = findOwned(view.sel);
      if (r && r.equip) equipTo(r.equip.slot, r.equip.id, r.equip.slot === "ring" ? ringTarget(r.equip.id) : undefined);
      return;
    }
    if (t.hasAttribute("data-swap-sidearm")) {
      window.EquipmentEngine.swapSidearm();
      view.pop = null;
      render();
    }
  }

  function onDblClick(ev) {
    var ct = ev.target && ev.target.closest ? ev.target.closest("[data-citem]") : null;
    if (ct) { doMove("take", ct.getAttribute("data-citem"), 1); return; }   // with a container open, a double-click moves one unit across
    var t = ev.target && ev.target.closest ? ev.target.closest("[data-item]") : null;
    if (t && view.left !== "you") { var it = findOwned(t.getAttribute("data-item")); if (it && it.stow) { doMove("stow", it.id, 1); return; } }
    if (t) quickAct(t.getAttribute("data-item"));
  }

  function open() {
    build();
    if (dlg.open) return;
    view.category = ""; view.sel = null; view.drag = null; view.pop = null; view.note = "";
    render();
    if (!dlg.showModal) { window.alert("This browser is too old to show the Inventory."); return; }
    dlg.showModal();
    placePop();
  }

  function close() { if (dlg && dlg.open) dlg.close(); }
  function toggle() { if (dlg && dlg.open) close(); else open(); }

